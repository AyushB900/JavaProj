CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(64) NOT NULL UNIQUE,
    balance NUMERIC(19,2) NOT NULL CHECK (balance >= 0),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE transfer_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_account_number VARCHAR(64) NOT NULL,
    destination_account_number VARCHAR(64) NOT NULL,
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    timestamp TIMESTAMP NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED')),
    CHECK (source_account_number <> destination_account_number)
);
CREATE INDEX idx_transfer_source_time ON transfer_transactions (source_account_number, timestamp);
CREATE INDEX idx_transfer_destination_time ON transfer_transactions (destination_account_number, timestamp);
